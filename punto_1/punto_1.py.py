import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp


# ============================================================
# FUNCIÓN PARA CONSTRUIR EL CAMPO DE PENDIENTES
# ============================================================

def campo_pendientes(ax, f, xlim=(-5, 5), ylim=(-5, 5), h=0.5):

    m = np.arange(xlim[0], xlim[1] + h, h)
    n = np.arange(ylim[0], ylim[1] + h, h)

    X, Y = np.meshgrid(m, n)

    pendiente = f(X, Y)


    norm = np.sqrt(1 + pendiente**2)

    U = 1 / norm
    V = pendiente / norm

    ax.quiver(
        X, Y, U, V,
        angles='xy',
        color='navy',
        alpha=0.6
    )

    ax.set_xlim(xlim)
    ax.set_ylim(ylim)

    ax.set_xlabel('x')
    ax.set_ylabel('y')

    ax.grid(alpha=0.2)


# ============================================================
# EJERCICIO 1(a)
# y' = -y - sin(x)
# y(0) = 1
# ============================================================

def f_a(x, y):
    return -y - np.sin(x)


x = np.linspace(-5, 5, 1000)

fig, ax = plt.subplots(figsize=(8, 6))

campo_pendientes(ax, f_a)

# Familia de soluciones
for C in [-3, -2, -1, 0, 1, 2, 3]:

    y = C * np.exp(-x) + (
        np.cos(x) - np.sin(x)
    ) / 2

    ax.plot(x, y, linewidth=1)


# Solución particular y(0)=1
y_particular = (
    0.5 * np.exp(-x)
    + (np.cos(x) - np.sin(x)) / 2
)

ax.plot(
    x,
    y_particular,
    linewidth=3,
    label='Solución particular: y(0)=1'
)

ax.set_title("Ejercicio 1(a)")
ax.legend()

plt.show()


