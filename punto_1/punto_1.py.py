# ============================================================
# EJERCICIO 1(e)
# y' = x e^y
#
# No tiene condición inicial.
# Elegimos y(0)=0.
# ============================================================

def f_e(x, y):
    return x * np.exp(y)


fig, ax = plt.subplots(figsize=(8, 6))

campo_pendientes(
    ax,
    f_e,
    xlim=(-2, 2),
    ylim=(-5, 5)
)


# Familia de soluciones
for C in [0.5, 1, 2, 4]:

    argumento = C - x**2 / 2

    y = np.full_like(x, np.nan)

    mascara = argumento > 0

    y[mascara] = -np.log(argumento[mascara])

    ax.plot(
        x,
        y,
        linewidth=1
    )


# Solución particular y(0)=0
argumento = 1 - x**2 / 2

y_particular = np.full_like(x, np.nan)

mascara = argumento > 0

y_particular[mascara] = -np.log(argumento[mascara])

ax.plot(
    x,
    y_particular,
    linewidth=3,
    label='Solución particular: y(0)=0'
)

ax.set_title("Ejercicio 1(e)")
ax.legend()

plt.show()


